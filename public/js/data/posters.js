// 'P41-P44,P50' → ['P41','P42','P43','P44','P50']
export function posterCodes(src = '') {
  const out = [];
  String(src).split(',').map((s) => s.trim()).filter(Boolean).forEach((s) => {
    const m = s.match(/^P(\d+)-P(\d+)$/);
    if (m) for (let n = +m[1]; n <= +m[2]; n++) out.push(`P${String(n).padStart(2, '0')}`);
    else out.push(s);
  });
  return out.filter((c) => POSTERS[c]);
}
