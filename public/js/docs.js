export function renderDoc({ view }, key) {
  const [title, html] = DOCS[key];
  view.innerHTML = `${pageHead(title)}<div class="doc">${html()}</div>`;
  // 목차: 같은 화면 안에서 해당 항목으로
  view.querySelectorAll('[data-to]').forEach((a) => a.addEventListener('click', (e) => {
    e.preventDefault();
    document.getElementById(a.dataset.to)?.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }));
}
